export function destinationPath(d: Pick<Destination, "region" | "countrySlug" | "citySlug">): string {
  return `/destinations/${d.region}/${d.countrySlug}/${d.citySlug}`;
}

export function getDestination(region: string, countrySlug: string, citySlug: string): Destination | undefined {
  return destinations.find((d) => d.region === region && d.countrySlug === countrySlug && d.citySlug === citySlug);
}

